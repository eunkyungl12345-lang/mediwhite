/** 특정 개인을 지칭하는 표현 감지(실명·직함). 완벽하지 않지만 올리기 전 한 번 멈추게 하는 용도 */
const _TITLES = "(선생님|쌤|샘|과장님?|원장님?|부장님?|팀장님?|실장님?|수간호사|간호사|의사|교수님?|대리님?|주임님?|사원|조무사|방사선사|치료사|병리사)";
// 성씨로 시작하는 2~3글자 이름에만 반응 (일반 문장 오탐 방지)
const SUR = "[김이박최정강조윤장임한오서신권황안송류유전홍고문양손배백허남심노하곽성차주우구민진나지엄채원천방공현함변염여추도소석선설마길연위표명기반왕금옥육인맹제모탁국어은편용예봉경사부]";
const HON = "(선생님|선생|쌤|샘|과장|원장|부장|팀장|실장|교수|대리|주임|수간호사|간호사|치료사|방사선사|병리사|조무사|교수님)";
const RE = [
  new RegExp(`${SUR}[가-힣](?![은는을의한던된운])[가-힣]\\s?${HON}`),                   // 김민지 간호사 / 홍길동 선생님 (세 글자 이름 + 호칭)
  new RegExp(`${SUR}(과장|원장|부장|팀장|실장|교수|대리|주임|쌤|샘|선생)`), // 김과장 / 박쌤
  new RegExp(`${SUR}[가-힣](?![은는을의한던된운])[가-힣]\\s?(씨|님)(?![가-힣])`),        // 홍길동씨 / 김민지님
  /[가-힣]{2,3}\s?\(\s?[가-힣]{2,10}\s?\)/,                  // 김OO(간호사)
  /010[-\s]?\d{3,4}[-\s]?\d{4}/,                              // 전화번호
  new RegExp(`${SUR}\\s?[OoㅇX*]{1,2}(\\s?[가-힣]|\\s)`),    // 김O수, 김ㅇㅇ 선생
];
export function personMention(text: string): string | null {
  for (const r of RE) { const m = text.match(r); if (m) return m[0]; }
  return null;
}
